const toggle=document.querySelector('.menu'),links=document.querySelector('.links');
toggle.addEventListener('click',()=>{const open=links.classList.toggle('open');
toggle.setAttribute('aria-expanded',String(open));
});
links.querySelectorAll('a').forEach(a=>a.addEventListener('click',()=>{links.classList.remove('open');
toggle.setAttribute('aria-expanded','false');
}));
document.addEventListener('keydown',e=>{if(e.key==='Escape'){links.classList.remove('open');
toggle.setAttribute('aria-expanded','false');
}});
document.getElementById('year').textContent=new Date().getFullYear();
